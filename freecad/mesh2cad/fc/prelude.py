import math as _m

import FreeCAD as App
import Part
import Sketcher

V = App.Vector

# section.PLANES as (u, v, n) world directions. XZ's normal is -Y, as the
# harness measures it, so its v is +Z.
_PLANE_AXES = {"XY": ((1, 0, 0), (0, 1, 0), (0, 0, 1)),
           "YZ": ((0, 1, 0), (0, 0, 1), (1, 0, 0)),
           "XZ": ((1, 0, 0), (0, 0, 1), (0, -1, 0))}
_AXIS = {"XY": 2, "YZ": 0, "XZ": 1}
_ACROSS = {0: "YZ", 1: "XZ", 2: "XY"}
_ADD = ("PartDesign::Pad", "PartDesign::Revolution")
_CUT = ("PartDesign::Pocket", "PartDesign::Groove")
_PATTERNS = ("PartDesign::PolarPattern", "PartDesign::LinearPattern",
             "PartDesign::Mirrored", "PartDesign::MultiTransform")
_JOIN = {"add": "Fuse", "cut": "Cut", "intersect": "Common", "separate": "Fuse"}


# ---- frames -----------------------------------------------------------------
def _frame(origin, u, v, n):
    """The placement whose x, y, z axes are u, v, n, at `origin`."""
    return App.Placement(App.Matrix(u[0], v[0], n[0], origin[0],
                                    u[1], v[1], n[1], origin[1],
                                    u[2], v[2], n[2], origin[2],
                                    0, 0, 0, 1))


def _plane_at(plane, level):
    """The sketch frame on XY / YZ / XZ at world coordinate `level` along its
    axis. Explicit on purpose: nothing here depends on how FreeCAD orients its
    own named planes."""
    u, v, n = _PLANE_AXES[plane]
    o = [0.0, 0.0, 0.0]
    o[_AXIS[plane]] = float(level)
    return _frame(o, u, v, n)


def _frame_xn(origin, x, n):
    """A frame at `origin` with z along `n` and x along `x` made square to it
    (y = z cross x): a blend's own plane, from the two directions measured."""
    n = V(*n).normalize()
    x = V(*x)
    x = (x - n * x.dot(n)).normalize()
    y = n.cross(x)
    return _frame(origin, tuple(x), tuple(y), tuple(n))


def _towards(point, normal):
    """A frame at `point` whose z is `normal` (a profile square to a path)."""
    return App.Placement(V(*point), App.Rotation(V(0, 0, 1), V(*normal)))


def _turn(about, angle):
    """A rotation by `angle` degrees about `about` through the origin -- how a
    feature measured in a frame (an inclined face or axis) is turned back."""
    return App.Placement(V(), App.Rotation(V(*about), angle))


# ---- document and bodies ----------------------------------------------------
def _start(name="reconstruction"):
    doc = App.newDocument(name)
    return doc, _body(doc, "Body")


def _body(doc, name, label=None, tool=False):
    """A PartDesign Body. AllowCompound: separate pieces, unfinished steps and
    multi-body parts must not make a feature Invalid -- the harness judges the
    pieces itself. A tool body (the second operand of a Boolean) is marked so
    `_finish` does not count it as part of the part."""
    b = doc.addObject("PartDesign::Body", name)
    if "AllowCompound" in b.PropertiesList:
        b.AllowCompound = True
    if label:
        b.Label = label
    if tool:
        b.addProperty("App::PropertyString", "M2C_Role", "m2c", "role in the part")
        b.M2C_Role = "tool"
        _hide(b)
    return b


def _part_bodies(doc):
    return [o for o in doc.Objects if o.TypeId == "PartDesign::Body"
            and getattr(o, "M2C_Role", "") != "tool"]


def _hide(obj):
    if App.GuiUp and getattr(obj, "ViewObject", None) is not None:
        obj.ViewObject.Visibility = False


def _origin(body, role):
    return next(f for f in body.Origin.OriginFeatures if f.Role == role)


# ---- blocks: one harness feature each ---------------------------------------
class _Block:
    def __init__(self, doc, name, mode, label):
        self.doc, self.name, self.mode, self.label = doc, name, mode, label
        self.mixed = False      # removes from its own solid -> tool body
        self.clipped = False    # clipped by a tool of its own (--with N) -> own Body
        self.piece = None       # the Body a clipped feature was built in
        self.nurbs = False      # the tool goes in as B-splines -> tool body
        self.frame = None       # placement the coordinates below are in
        self.body, self.sub, self.tool = None, False, False
        self.features, self.transforms, self.n = [], [], {}


def _block(doc, name, mode="add", label=None):
    if mode not in _JOIN:
        raise ValueError(f"block {name}: mode {mode!r} is not add/cut/intersect/separate")
    return _Block(doc, name, mode, label)


def _resolve(B):
    """The Body this block's features go into, decided on first use (after
    `mixed` / `nurbs` are known)."""
    if B.body is not None:
        return B.body
    parts = _part_bodies(B.doc)
    if B.mode == "separate":
        B.body = _body(B.doc, B.name + "_Body", label=B.label)
    elif B.clipped:
        B.body, B.tool = _body(B.doc, B.name + "_Piece", tool=True,
                               label=(B.label or B.name) + " (before clipping)"), True
    elif B.mode == "add" and not (B.mixed or B.nurbs):
        B.body = parts[-1] if parts else _body(B.doc, "Body")
    elif B.mode == "cut" and not (B.mixed or B.nurbs) and len(parts) == 1:
        B.body, B.sub = parts[0], True
    else:
        B.body, B.tool = _body(B.doc, B.name + "_Tool", tool=True,
                               label=(B.label or B.name) + " (tool)"), True
    return B.body


def _ctx(b):
    """(body, block or None) for a block or a plain Body."""
    if isinstance(b, _Block):
        return _resolve(b), b
    return b, None


def _name(B, kind):
    if B is None:
        return kind
    k = B.n.get(kind, 0)
    B.n[kind] = k + 1
    return f"{B.name}_{kind}" + (str(k) if k else "")


def _place(B, pl, world=False):
    if B is not None and B.frame is not None and not world:
        return B.frame.multiply(pl)
    return pl


# ---- sketches ----------------------------------------------------------------
def _sketch(b, placement, name=None, label=None, world=False):
    """A sketch attached to its Body's XY plane at `placement` (a frame from
    _plane_at, or an inclined one): the placement IS the sketch plane. In a
    block with a frame, `placement` is in that frame."""
    body, B = _ctx(b)
    sk = body.newObject("Sketcher::SketchObject", name or _name(B, "Sketch"))
    sk.AttachmentSupport = [(_origin(body, "XY_Plane"), "")]
    sk.MapMode = "ObjectXY"
    sk.AttachmentOffset = _place(B, placement, world)
    if label:
        sk.Label = label
    _hide(sk)
    return sk


def _arc_ccw(c, r, a, b, ccw):
    """Sketcher arcs run CCW from their first angle to their second, so a CW
    arc is the same arc with its ends swapped. Returns (geometry, vertex the
    traversal starts at, vertex it ends at)."""
    lo, hi = (a, b) if ccw else (b, a)
    while hi <= lo:
        hi += 2 * _m.pi
    g = Part.ArcOfCircle(Part.Circle(V(c[0], c[1], 0), V(0, 0, 1), r), lo, hi)
    return g, (1, 2) if ccw else (2, 1)


def _three_point(p0, pm, p1):
    (x1, y1), (x2, y2), (x3, y3) = p0, pm, p1
    d = 2 * (x1 * (y2 - y3) + x2 * (y3 - y1) + x3 * (y1 - y2))
    cx = ((x1 * x1 + y1 * y1) * (y2 - y3) + (x2 * x2 + y2 * y2) * (y3 - y1)
          + (x3 * x3 + y3 * y3) * (y1 - y2)) / d
    cy = ((x1 * x1 + y1 * y1) * (x3 - x2) + (x2 * x2 + y2 * y2) * (x1 - x3)
          + (x3 * x3 + y3 * y3) * (x2 - x1)) / d
    ccw = (x2 - x1) * (y3 - y2) - (y2 - y1) * (x3 - x2) > 0
    return (cx, cy), ccw


_COINCIDENT_MAX = 512


def _ring(sk, segs, closed=True):
    """A ring (or, closed=False, an open path) of consecutive segments in
    sketch coordinates:

        ("L", p0, p1)              a line
        ("A", p0, p1, c, ccw)      an arc from p0 to p1 about centre c
        ("A3", p0, pm, p1)         an arc through three points

    Every joint gets a Coincident constraint, so the wire is closed by
    construction rather than by the coordinates happening to agree.

    Geometry and constraints go in as ONE call each: added one at a time the
    sketch re-solves after every call, and a conformed ring of a few hundred
    vertices takes minutes. Past
    _COINCIDENT_MAX segments the joints are not constrained at all: the
    solver's cost grows with the cube of the ring (1500 lines took 7 s, 3000
    nearly a minute), and the ring is closed anyway -- each segment starts on
    the very point the last one ended on, written once."""
    geoms, ends = [], []
    for s in segs:
        if s[0] == "L":
            g, (a, b) = Part.LineSegment(V(*s[1], 0), V(*s[2], 0)), (1, 2)
        else:
            if s[0] == "A3":
                p0, p1 = s[1], s[3]
                c, ccw = _three_point(s[1], s[2], s[3])
            else:
                p0, p1, c, ccw = s[1], s[2], s[3], s[4]
            r = _m.hypot(p0[0] - c[0], p0[1] - c[1])
            g, (a, b) = _arc_ccw(c, r, _m.atan2(p0[1] - c[1], p0[0] - c[0]),
                                 _m.atan2(p1[1] - c[1], p1[0] - c[0]), ccw)
        geoms.append(g)
        ends.append((a, b))
    first = sk.GeometryCount
    ids = sk.addGeometry(geoms) if len(geoms) > 1 else [sk.addGeometry(geoms[0])]
    ids = list(ids) if ids else list(range(first, first + len(geoms)))
    n = len(ids)
    cons = [Sketcher.Constraint("Coincident", ids[i], ends[i][1], ids[(i + 1) % n],
                                ends[(i + 1) % n][0])
            for i in range(n) if closed or i < n - 1] if n <= _COINCIDENT_MAX else []
    if cons:
        sk.addConstraint(cons)
    return ids


def _polygon(sk, pts):
    pts = [tuple(p) for p in pts]
    if pts[0] == pts[-1]:
        pts = pts[:-1]
    return _ring(sk, [("L", a, b) for a, b in zip(pts, pts[1:] + pts[:1], strict=True)])


def _circle(sk, c, r):
    return sk.addGeometry(Part.Circle(V(c[0], c[1], 0), V(0, 0, 1), r))


# ---- datums --------------------------------------------------------------------
def _datum_line(b, point, direction, name=None, world=False):
    """A datum axis through `point` along `direction`. Not attached: in
    FreeCAD 1.1 an attached PartDesign::Line comes out Invalid or empty in
    every mode tried, and an explicit placement references nothing that
    topological naming could break."""
    body, B = _ctx(b)
    pl = _place(B, App.Placement(V(*point), App.Rotation(V(0, 0, 1), V(*direction))),
                world)
    ln = body.newObject("PartDesign::Line", name or _name(B, "Axis"))
    ln.MapMode = "Deactivated"
    ln.Placement = pl
    _hide(ln)
    return ln


def _axis_in(b, placement, p0, p1, name=None, world=False):
    """The datum axis through two points of a sketch plane, p0 -> p1 in its
    (u, v) -- the axis a revolve names in the profile's own plane."""
    a = placement.multVec(V(p0[0], p0[1], 0))
    d = placement.Rotation.multVec(V(p1[0] - p0[0], p1[1] - p0[1], 0))
    body, B = _ctx(b)
    if B is not None and B.frame is not None and not world:
        a, d = B.frame.multVec(a), B.frame.Rotation.multVec(d)
    return _datum_line(b, (a.x, a.y, a.z), (d.x, d.y, d.z), name=name, world=True)


def _datum_plane(b, placement, name=None, world=False):
    body, B = _ctx(b)
    p = body.newObject("PartDesign::Plane", name or _name(B, "Plane"))
    p.AttachmentSupport = [(_origin(body, "XY_Plane"), "")]
    p.MapMode = "ObjectXY"
    p.AttachmentOffset = _place(B, placement, world)
    _hide(p)
    return p


# ---- solid features --------------------------------------------------------------
def _plain(f):
    """No "Refine" (FreeCAD >= 1.0 turns it on for every new feature): a Pad
    fused onto a refined Body can come back as the Pad alone, Up-to-date and
    without a word, where the same two solids fuse right in Part, and right
    in PartDesign once no feature refines. The geometry is
    the same either way; only coplanar faces stay split."""
    if "Refine" in f.PropertiesList:
        f.Refine = False
    return f


def _feature(b, add, sub, minus, name, label):
    """A solid feature of the right kind: additive unless the block cuts
    (or `minus`); a feature that removes from a cut block's own solid has no
    PartDesign equivalent and needs the block marked mixed (tool body)."""
    body, B = _ctx(b)
    cut = B.sub if B is not None else False
    if cut and minus:
        raise RuntimeError(f"block {B.name}: a feature that removes from the "
                           f"block's own solid needs `.mixed = True` before the "
                           f"block's first feature")
    kind = sub if cut != bool(minus) else add
    f = _plain(body.newObject(f"PartDesign::{kind}", name or _name(B, kind)))
    if label:
        f.Label = label
    elif B is not None and B.label and not B.features:
        # In a tool body the block's label belongs to the Boolean that joins
        # it to the part; FreeCAD keeps labels unique by renumbering the
        # second one's trailing digits, which turns "X -54.97->54.97" into
        # "X -54.97->54.001".
        f.Label = B.label + (" (in its tool body)" if B.tool else "")
    if B is not None:
        B.features.append(f)
    return body, f


def _tip(body, f):
    """Make `f` the Body's Tip. body.newObject() does not move it for the
    pattern features, and without this the next feature chains onto the
    pattern's original and the copies silently drop out of the part."""
    body.Tip = f
    return f


def _pad(b, sk, length, side="one", length2=None, reversed=False, taper=0.0,
         minus=False, cut=False, name=None, label=None):
    """Pad (Pocket in a cut block, or minus=True) of a sketch along its normal.

    side: "one" -- `length` along the normal (against it if reversed);
          "two" -- `length` along it and `length2` against it;
          "sym" -- `length` IN TOTAL, centred on the sketch (FreeCAD's
                   Symmetric length is the total, not each side's).
    taper: degrees, FreeCAD's sign -- positive widens the section along the
           travel (the same for a Pocket).

    The same arguments give the same SOLID whether it becomes a Pad or a
    Pocket: measured, a Pocket runs against the sketch normal where a Pad runs
    along it (and its two sides swap), so a Pocket's `Reversed` is inverted."""
    body, f = _feature(b, "Pad", "Pocket", minus or cut, name, label)
    if f.TypeId == "PartDesign::Pocket":
        reversed = not reversed
    f.Profile = sk
    f.Length = length
    if "SideType" in f.PropertiesList:                    # FreeCAD >= 1.1
        f.SideType = {"one": "One side", "two": "Two sides", "sym": "Symmetric"}[side]
    elif side == "sym":
        f.Midplane = True
    elif side == "two":
        f.Type = "TwoLengths"
    if length2 is not None:
        f.Length2 = length2
    f.Reversed = bool(reversed)
    if taper:
        f.TaperAngle = taper
    return _tip(body, f)


def _pocket(b, sk, length, **kw):
    return _pad(b, sk, length, minus=True, **kw)


def _revolve(b, sk, axis, angle=360.0, minus=False, cut=False, name=None, label=None):
    """Revolution (Groove in a cut block, or minus=True) about a datum axis."""
    body, f = _feature(b, "Revolution", "Groove", minus or cut, name, label)
    f.Profile = sk
    f.ReferenceAxis = (axis, [""])
    f.Angle = angle
    return _tip(body, f)


def _loft(b, sections, ruled=False, minus=False, cut=False, name=None, label=None):
    """A loft through sketches in order. Sections may carry inner wires."""
    body, f = _feature(b, "AdditiveLoft", "SubtractiveLoft", minus or cut, name, label)
    f.Profile = sections[0]
    f.Sections = list(sections[1:])
    f.Ruled = bool(ruled)
    return _tip(body, f)


def _pipe(b, profile, spine, mode="Standard", transition=None, minus=False,
          cut=False, sections=None, name=None, label=None):
    """`profile` swept along every edge of `spine` (a sketch, a Part::Helix or
    a `_path`). With `sections`, the profile is carried through each of them
    in turn (Transformation "Multisection": without it FreeCAD keeps the
    profile and ignores the sections -- measured, a 20 -> 12 mm square came
    out a 20 mm one). A Pipe FreeCAD refuses, or builds to another volume
    than OCC's own sweep, is swept again with OCC's own sweep
    (`_swept_instead`)."""
    body, f = _feature(b, "AdditivePipe", "SubtractivePipe", minus or cut, name, label)
    f.Profile = profile
    f.Spine = (spine, [f"Edge{i + 1}" for i in range(len(spine.Shape.Edges))])
    f.Mode = mode
    if transition:
        f.Transition = transition
    if sections:
        f.Sections = list(sections)
        f.Transformation = "Multisection"
    _tip(body, f)
    return _swept_instead(b, f, profile, spine, mode, transition, sections)


# A PartDesign Pipe's transitions, as Part's makePipeShell numbers them.
_TRANSITIONS = {"Transformed": 0, "Right corner": 1, "Round corner": 2}
# A Pipe whose own solid is further than this share from OCC's sweep is not kept.
_PIPE_AGREE = 0.01


def _swept(profile, spine, frenet, transition, sections=None):
    """The sweep from OCC's MakePipeShell at its own tolerances: each wire of
    `profile` swept on its own and the inner ones cut from the outer; with
    `sections`, one wire per sketch carried through them in order."""
    path = Part.Wire(spine.Shape.Edges)
    how = _TRANSITIONS.get(transition, 0)
    if sections:
        wires = [sk.Shape.Wires[0] for sk in [profile, *sections]]
        return path.makePipeShell(wires, True, frenet, how)
    wires = sorted(profile.Shape.Wires, key=lambda w: Part.Face(w).Area, reverse=True)
    solid = path.makePipeShell([wires[0]], True, frenet, how)
    for w in wires[1:]:
        solid = solid.cut(path.makePipeShell([w], True, frenet, how))
    return solid


def _swept_instead(b, f, profile, spine, mode, transition, sections):
    """`f` as FreeCAD built it; or, when FreeCAD refused it or built it to
    another volume than OCC's own sweep, the same sweep from `_swept` in its
    place.

    FreeCAD's Pipe sweeps at Precision::Confusion and closes the ends itself.
    Along a long B-spline that turns through 180 deg it can refuse sweeps
    ("BRep_API: command not done") that MakePipeShell at its default
    tolerances builds valid; through two sections it
    can build a thin slab of negative volume, without a word. So the Pipe is kept only when its own solid is within
    `_PIPE_AGREE` of `_swept`'s. Otherwise the swept solid replaces it as a
    stored solid: the Body's base when the Pipe was its first solid, else a
    tool Body joined where the Pipe stood (Fuse, or Cut for a subtractive
    Pipe). A sweep `_swept` cannot build either stays as FreeCAD left it, for
    `--check` to report."""
    body, B = _ctx(b)
    doc = body.Document
    doc.recompute()
    refused = any(s in ("Invalid", "Error") for s in f.State) or f.Shape.isNull()
    cut = f.TypeId == "PartDesign::SubtractivePipe"
    base = f.BaseFeature
    if mode not in ("Standard", "Frenet") or (cut and base is None):
        return f
    try:
        solid = _swept(profile, spine, mode == "Frenet", transition, sections)
        ok = not solid.isNull() and solid.isValid() and solid.Volume > 0
    except Exception:                                              # noqa: BLE001
        ok = False
    if not ok:
        return f
    if refused:
        why = "FreeCAD's Pipe refused it"
    else:
        own = f.AddSubShape
        made = 0.0 if own.isNull() else own.Volume
        if abs(made - solid.Volume) <= _PIPE_AGREE * solid.Volume:
            return f
        why = f"FreeCAD's Pipe made {made:.0f} mm^3 of it"
    name = f.Name
    label = (f.Label + f" (OCC sweep: {why})")[:120]
    if B is not None:
        B.features = [x for x in B.features if x is not f]
    body.removeObject(f)
    doc.removeObject(name)
    shell = doc.addObject("Part::Feature", name + "_Swept")
    shell.Shape = _baked(solid)
    _hide(shell)
    if base is None:
        shell.Label = label
        body.BaseFeature = shell
        if body.Tip is None:
            body.Tip = shell
        out = shell
    else:
        tool = _body(doc, name + "_Tool", label=label[:113] + " (tool)", tool=True)
        tool.BaseFeature = shell
        out = _boolean(body, [tool], name + "_Join", "Cut" if cut else "Fuse", label=label)
    if B is not None:
        B.features.append(out)
    doc.recompute()
    return out


def _helix(b, sk, axis, pitch, height, left=False, minus=False, cut=False,
           name=None, label=None):
    body, f = _feature(b, "AdditiveHelix", "SubtractiveHelix", minus or cut, name, label)
    f.Profile = sk
    f.ReferenceAxis = (axis, [""])
    f.Mode = "pitch-height-angle"
    f.Pitch, f.Height, f.Angle = pitch, height, 0.0
    f.LeftHanded = bool(left)
    return _tip(body, f)


def _sphere(b, centre, r, minus=False, name=None, label=None):
    """A ball at `centre` (in the block's frame): a round end of a wire."""
    body, B = _ctx(b)
    body, f = _feature(b, "AdditiveSphere", "SubtractiveSphere", minus, name, label)
    f.Radius = r
    f.MapMode = "Deactivated"
    f.Placement = _place(B, App.Placement(V(*centre), App.Rotation()))
    return _tip(body, f)


def _helix_path(b, pitch, height, radius, base=0.0, left=False, phase=0.0, name=None):
    """A Part::Helix about +Z from `base`, turned `phase` degrees -- the path
    a round wire is swept along. Kept beside the Body as the pipe's spine."""
    body, B = _ctx(b)
    h = body.Document.addObject("Part::Helix", name or _name(B, "Helix"))
    h.Pitch, h.Height, h.Radius = pitch, height, radius
    h.LocalCoord = "Left-handed" if left else "Right-handed"
    h.Placement = _place(B, App.Placement(V(0, 0, base), App.Rotation(V(0, 0, 1), phase)))
    _hide(h)
    h.recompute()
    return h


def _helix_start(h):
    """The frame square to a helix at its start: where its profile goes."""
    e = h.Shape.Edges[0]
    return _towards(tuple(e.valueAt(e.FirstParameter)),
                    tuple(e.tangentAt(e.FirstParameter)))


def _path(b, pieces, name=None, world=False):
    """A 3-D path, kept beside the Body as a pipe's spine: one edge per piece,
    in order, in world coordinates (the block's frame, if it has one):

        ("L", p0, p1)              a line
        ("A3", p0, pm, p1)         an arc through three points
        ("S", p0, p1, ...)         a spline through the points

    A sketch is planar and a path across a bend need not be, so the path is a
    Part::Feature: stored in the .FCStd, rebuilt by this program on every run.
    A spline is interpolated through its points (chord-length
    parametrization)."""
    body, B = _ctx(b)
    edges = []
    for q in pieces:
        pts = [V(*p) for p in q[1:]]
        if q[0] == "L":
            edges.append(Part.LineSegment(pts[0], pts[1]).toShape())
        elif q[0] == "A3":
            edges.append(Part.Arc(pts[0], pts[1], pts[2]).toShape())
        else:
            c = Part.BSplineCurve()
            c.interpolate(pts)
            edges.append(c.toShape())
    w = Part.Wire(edges)
    pl = _place(B, App.Placement(), world)
    if not pl.isIdentity():
        w.transformShape(pl.toMatrix(), True)
    o = body.Document.addObject("Part::Feature", name or _name(B, "Path"))
    o.Shape = w
    _hide(o)
    return o


def _baked(shape):
    """`shape` with its placement moved into the geometry. A Body's
    BaseFeature takes a shape WITHOUT its placement: a coil turned onto Y comes
    back along Z. Every solid that becomes a BaseFeature goes
    through here, so it stays where it was computed."""
    if shape.Placement.isIdentity():
        return shape
    pl = shape.Placement
    out = shape.copy()
    out.Placement = App.Placement()
    out.transformShape(pl.toMatrix(), True)
    return out


def _stored(b, shape, name=None, label=None):
    """A solid the program computes itself (a thread's ruled coil), as the
    base of its block's Body: kept in the .FCStd as a shape and rebuilt by
    this program on every run. The block must be mixed (its own Body)."""
    body, B = _ctx(b)
    if body.Group and any(o.TypeId.startswith("PartDesign::") and o.TypeId not in
                          ("PartDesign::Line", "PartDesign::Plane") for o in body.Group):
        raise RuntimeError("a stored solid must be the first feature of its Body")
    nf = body.Document.addObject("Part::Feature", name or _name(B, "Solid"))
    nf.Shape = _baked(shape)
    if label:
        nf.Label = label
    _hide(nf)
    body.BaseFeature = nf
    if B is not None:
        B.features.append(nf)
    return nf


def _wire_of(pl, segs):
    """A closed wire of ("L", p0, p1) / ("A3", p0, pm, p1) segments drawn in
    the (u, v) of placement `pl`, in world coordinates."""
    def w(p):
        return pl.multVec(V(p[0], p[1], 0))
    edges = []
    for s in segs:
        if s[0] == "L":
            edges.append(Part.LineSegment(w(s[1]), w(s[2])).toShape())
        else:
            edges.append(Part.Arc(w(s[1]), w(s[2]), w(s[3])).toShape())
    return Part.Wire(edges)


def _blend_clipped(how, pl, segs, size, clips):
    """A blend solid cut down where the part ends at a slant across it: the
    outline `segs` in placement `pl` padded `size` along its normal
    (how "prism") or revolved `size` degrees about the placement's y axis,
    then intersected with each clip (placement, loops of (u, v) points, depth:
    the loops padded `depth` along that placement's normal). A Part solid,
    stored as its block's base solid: a PartDesign Body cannot clip one of its
    own features and not the rest."""
    face = Part.Face(_wire_of(pl, segs))
    if how == "prism":
        s = face.extrude(pl.Rotation.multVec(V(0, 0, size)))
    else:
        s = face.revolve(pl.Base, pl.Rotation.multVec(V(0, 1, 0)), size)
    for cpl, loops, depth in clips:
        ws = [_wire_of(cpl, [("L", a, b) for a, b in zip(lp, lp[1:] + lp[:1], strict=True)])
              for lp in loops]
        cf = Part.makeFace(ws, "Part::FaceMakerBullseye")
        s = s.common(cf.extrude(cpl.Rotation.multVec(V(0, 0, depth))))
    return s


def _ruled_coil(pts, pitch, height, lefthand, turn_end, band, r_max, theta=0.0,
                turn=0, centre=(0, 0, 0)):
    """A profile carried along a helix as a RULED solid, trimmed to `band`.

    `pts` is the profile in the helix's local frame -- (r, z), the axis along
    z. Every vertex is wound round the axis as its own helix, neighbouring
    helices bound one ruled face, the profile caps both ends, and the shell is
    the solid. Not OCC's sweep, which on a tooth profile may not mesh closed
    and comes out too big; the ruled solid is valid and meshes closed. The
    local frame is then turned onto the world's (`turn` degrees about
    (1,1,1) cycles the axes) and moved to `centre`."""
    hel = []
    for r, z in pts:
        h = Part.makeHelix(pitch, height, r, 0, bool(lefthand))
        h.translate(V(0, 0, z))
        hel.append(h.Edges[0])
    # Orientation 1: rule each helix to its neighbour start-to-start. The
    # default lets the kernel choose, and between two helices of different
    # radius it ruled one's start to the other's end -- an open, twisted shell.
    faces = [Part.makeRuledSurface(hel[i], hel[(i + 1) % len(hel)], 1)
             for i in range(len(hel))]
    cap = Part.Face(Part.makePolygon([V(r, 0, z) for r, z in pts], True))
    cap1 = cap.copy()
    cap1.rotate(V(0, 0, 0), V(0, 0, 1), turn_end)
    cap1.translate(V(0, 0, height))
    sewn = Part.makeCompound(faces + [cap, cap1])
    sewn.sewShape()                             # one closed shell
    coil = Part.Solid(sewn.Shells[0])
    if coil.Volume < 0:
        coil.reverse()
    za, zb = band
    cyl = Part.makeCylinder(r_max + 1.0, zb - za, V(0, 0, za))
    got = coil.common(cyl)
    if not got.Solids or not got.isValid():
        got = coil.common([cyl], 0.01)          # fuzzy Boolean, 0.01 mm
    if not got.Solids:
        # A coil empty either way is said by name, not passed on empty.
        raise ValueError(f"the swept coil is void inside its band z={za:g}..{zb:g} "
                         f"(local): the turns do not meet the band, or they overlap "
                         f"each other")
    if abs(theta) > 1e-9:
        got.rotate(V(0, 0, 0), V(0, 0, 1), theta)
    if turn:
        got.rotate(V(0, 0, 0), V(1, 1, 1), turn)
    got.translate(V(*centre))
    return got


# ---- patterns ------------------------------------------------------------------
def _polar_block(B, p0, p1, n):
    """The block's features repeated n times about the world axis p0 -> p1."""
    B.transforms.append(("polar", tuple(p0), tuple(p1), int(n)))


def _linear_block(B, step, n):
    """The block's features repeated n times, each `step` on from the last."""
    B.transforms.append(("linear", tuple(step), int(n)))


def _mirror_block(B, k, coord):
    """The block's features and their mirror image in the plane across world
    axis k (0 X, 1 Y, 2 Z) at `coord`."""
    B.transforms.append(("mirror", int(k), float(coord)))


def _matrices(t):
    """Every placement a transform makes, identity first, as Matrices."""
    if t[0] == "polar":
        c, d = V(*t[1]), V(*t[2]) - V(*t[1])
        return [App.Placement(V(), App.Rotation(d, k * 360.0 / t[3]), c).toMatrix()
                for k in range(t[3])]
    if t[0] == "linear":
        return [App.Placement(V(*t[1]) * k, App.Rotation()).toMatrix() for k in range(t[2])]
    m = App.Matrix()
    setattr(m, ("A11", "A22", "A33")[t[1]], -1.0)
    setattr(m, ("A14", "A24", "A34")[t[1]], 2.0 * t[2])
    return [App.Matrix(), m]


def _transform_feature(body, B, t, sub=True):
    """The PartDesign feature for one transform (standalone, or as a
    sub-transformation of a MultiTransform when sub=True)."""
    if t[0] == "polar":
        ax = _datum_line(B, t[1], tuple(V(*t[2]) - V(*t[1])), world=True)
        f = _plain(body.newObject("PartDesign::PolarPattern", _name(B, "Polar")))
        f.Axis = (ax, [""])
        f.Angle, f.Occurrences = 360.0, t[3]
    elif t[0] == "linear":
        step = V(*t[1])
        ax = _datum_line(B, (0, 0, 0), tuple(step), world=True)
        f = _plain(body.newObject("PartDesign::LinearPattern", _name(B, "Linear")))
        f.Direction = (ax, [""])
        f.Mode, f.Length, f.Occurrences = "Extent", step.Length * (t[2] - 1), t[2]
    else:
        pl = _datum_plane(B, _plane_at(_ACROSS[t[1]], t[2]), world=True)
        f = _plain(body.newObject("PartDesign::Mirrored", _name(B, "Mirror")))
        f.MirrorPlane = (pl, [""])
    return f


def _patterns(B):
    """Apply the block's transforms to its features: one pattern feature, or
    a MultiTransform when a --pattern is mirrored too (the copies, then their
    image)."""
    body = B.body
    if len(B.transforms) == 1:
        f = _transform_feature(body, B, B.transforms[0])
        f.Originals = list(B.features)
    else:
        subs = [_transform_feature(body, B, t) for t in B.transforms]
        f = _plain(body.newObject("PartDesign::MultiTransform", _name(B, "MultiTransform")))
        f.Originals = list(B.features)
        f.Transformations = subs
    mats = [App.Matrix()]
    for t in B.transforms:
        mats = [b.multiply(a) for b in _matrices(t) for a in mats]
    f.addProperty("App::PropertyFloatList", "M2C_Transforms", "m2c",
                  "the copies this pattern adds, as 4x4 matrices (row major)")
    f.M2C_Transforms = [x for m in mats[1:] for x in m.A]
    if B.label:
        f.Label = B.label + " (pattern)"
    return _tip(body, f)


def _clip(B):
    """`--combine intersect --with N`: everything the block built so far is the
    feature; what follows is the tool that clips it, and only it. The feature's
    own patterns are applied now; the tool gets a Body of its own."""
    if B.piece is not None:
        raise RuntimeError(f"block {B.name} is clipped twice")
    _resolve(B)
    if B.transforms:
        _patterns(B)
    B.piece, B.frame = B.body, None
    B.features, B.transforms, B.mixed = [], [], False
    B.body = _body(B.doc, B.name + "_Clip", tool=True,
                   label=(B.label or B.name) + " (clipping tool)")


def _end(B):
    """Close the block: its patterns, then -- when it was built in a tool
    Body -- the Booleans that join it to the part. A tool cuts or clips EVERY
    part Body; an added one fuses into
    the last."""
    if B.body is None:
        raise RuntimeError(f"block {B.name} built nothing")
    if B.transforms:
        _patterns(B)
    B.frame = None
    _cut_that_is_valid(B)
    if B.piece is not None:
        # The clipped feature: its own Body, intersected with the tool's.
        common = _boolean(B.piece, [B.body], f"{B.name}_Clipped", "Common",
                          label=(B.label or B.name) + " (clipped)")
        B.body = _clip_that_holds(B, common, B.body)
        if B.mode == "separate":                 # a body of its own: it stays one
            B.body.M2C_Role = ""
            B.tool = False
    if not B.tool:
        return B.body
    tool = B.body
    if B.nurbs:
        tool = _nurbs_tool(B.doc, B.name + "_Cutter", B.body,
                           label=(B.label or B.name) + " (B-spline cutter)")
    parts = _part_bodies(B.doc)
    kind = _JOIN[B.mode]
    targets = parts[-1:] if B.mode == "add" else parts
    for i, t in enumerate(targets):
        f = _boolean(t, [tool], f"{B.name}_{kind}" + (str(i) if i else ""), kind,
                     label=B.label if i == 0 else None)
        if B.nurbs and kind == "Cut":
            _cut_that_holds(f, B.body)
        elif not B.nurbs:
            _boolean_that_holds(f, tool)
    return tool


def _cut_that_is_valid(B):
    """A cut in the part's own Body that FreeCAD built as an invalid solid, made
    again with its tool as B-splines.

    A small fillet Groove on a convex edge can come out Up-to-date as an
    invalid solid, and Part's cut of the same two shapes is the same invalid
    solid. With the tool as B-splines the cut is valid, and the features'
    meshes converge on its volume. So a block's
    one cut, when its result is invalid and the B-spline cut in Part is valid,
    becomes a tool Body of the B-spline cutter, cut where the feature stood. A
    patterned block, or one of more features, is left as it was."""
    if B.tool or B.transforms or not B.sub or len(B.features) != 1:
        return
    f = B.features[0]
    if not (f.TypeId in _CUT or f.TypeId.startswith("PartDesign::Subtractive")):
        return
    doc = B.doc
    doc.recompute()
    sh, base = f.Shape, getattr(f, "BaseFeature", None)
    if sh.isNull() or sh.isValid() or base is None or base.Shape.isNull():
        return
    try:
        own = f.AddSubShape
        if own.isNull() or not own.isValid():
            return
        nurbs = own.toNurbs()
        made = base.Shape.cut(nurbs)
        if made.isNull() or not made.isValid():
            return
    except Exception:                                              # noqa: BLE001
        return
    body, name = B.body, f.Name
    label = (f.Label + " (B-spline cut: FreeCAD built the analytic one invalid)")[:120]
    body.removeObject(f)
    doc.removeObject(name)
    nf = doc.addObject("Part::Feature", name + "_Cutter")
    nf.Shape = _baked(nurbs)
    _hide(nf)
    tb = _body(doc, name + "_Tool", label=label[:113] + " (tool)", tool=True)
    tb.BaseFeature = nf
    B.features = [_boolean(body, [tb], name + "_Cut", "Cut", label=label)]
    doc.recompute()


# A Boolean further than this share from Part's own Boolean of the same shapes is
# not kept as it is.
_BOOL_AGREE = 1e-4


def _clip_that_holds(B, common, clip):
    """The Body that holds the clipped feature: B.piece when its Common is the
    feature clipped; else a tool Body of the feature clipped step by step in
    Part.

    Pads in a polar pattern -- one solid -- clipped by a revolve can give a
    PartDesign Common of negative volume. Part's common of the same two shapes
    can be empty, fuzzy no better, and as B-splines invalid, while one pad
    clipped alone is valid. So the feature is clipped in the order it was built: each solid it
    adds (a pattern's copies one by one) intersected with the clip, each one it
    removes cut from what is there. That is the same solid, since
    (X - Y) & C = (X & C) - Y. The Common stays in the tree, unused."""
    doc = common.Document
    doc.recompute()
    want = None
    try:
        for f in _chain(B.piece):
            for op, s in _feature_steps(f):
                if op == "add":
                    s = s.common(clip.Shape)
                    want = s if want is None else want.fuse(s)
                elif op == "cut" and want is not None:
                    want = want.cut(s)
        if want is None or want.isNull() or not want.isValid() or want.Volume <= 0:
            return B.piece
    except Exception:                                              # noqa: BLE001
        return B.piece
    sh = common.Shape
    if (not sh.isNull() and sh.isValid()
            and abs(sh.Volume - want.Volume) <= _BOOL_AGREE * max(want.Volume, 1.0)):
        return B.piece
    label = ((B.label or B.name) + " (clipped step by step: the Common did not hold)")[:113]
    nf = doc.addObject("Part::Feature", B.name + "_ClippedSolid")
    nf.Shape = _baked(want)
    nf.Label = label
    _hide(nf)
    tb = _body(doc, B.name + "_ClippedCopies", tool=True, label=label + " (tool)")
    tb.BaseFeature = nf
    return tb


def _boolean_that_holds(f, tool):
    """Keep a PartDesign Boolean only when it is what Part makes of the same two
    shapes; else redo it with its tool as B-splines.

    PartDesign's Boolean can cut a part down to nothing, Up-to-date and
    without a word, where Part's cut of the same two shapes is right; a
    clipped fillet wedge of planes and a cylinder that passes BRepCheck is
    enough. Fixing or refining it does not help; the same wedge as B-splines
    PartDesign cuts right. So a Boolean whose result is invalid, or
    further than `_BOOL_AGREE` from Part's, takes its tool as B-splines
    (`_nurbs_tool`, the analytic Body staying in the tree, unused). If that
    does not hold either, the Boolean is left as it was, for `--check` to
    report."""
    doc = f.Document
    doc.recompute()
    base = getattr(f, "BaseFeature", None)
    if base is None or base.Shape.isNull() or tool.Shape.isNull():
        return f
    try:
        want = getattr(base.Shape, {"Cut": "cut", "Fuse": "fuse", "Common": "common"}[f.Type])(
            tool.Shape)
    except Exception:                                              # noqa: BLE001
        return f
    tol = _BOOL_AGREE * max(abs(base.Shape.Volume), abs(want.Volume), 1.0)

    def holds():
        sh = f.Shape
        if sh.isNull():
            return want.isNull() or abs(want.Volume) <= tol
        return sh.isValid() and abs(sh.Volume - want.Volume) <= tol

    if holds():
        return f
    tools = list(f.Group)
    try:
        nurbs = _nurbs_tool(doc, f.Name + "_Bspline", tool,
                            label=(f.Label + " (B-spline tool)")[:120])
    except Exception:                                              # noqa: BLE001
        return f
    f.setObjects([nurbs])
    doc.recompute()
    if holds():
        f.Label = (f.Label + " (B-spline tool: the analytic one did not hold)")[:120]
        return f
    f.setObjects(tools)
    doc.recompute()
    return f


def _cut_that_holds(f, analytic):
    """Keep a B-spline cut only when it is plausible, else cut analytically.

    The B-spline cutter is there because OCC cuts a tilted cone or cylinder out
    of a revolved body wrongly in analytic form. It can fail the other way
    too: the B-spline copy of crossing pin holes cut out of a cone can remove
    far more than the cutter holds, where the analytic cut is right. A cut can
    remove at most the cutter's own volume, and never add any, so the
    B-spline result is checked against that and, failing it, the same
    Boolean takes the analytic tool body instead (the B-spline one stays in
    the tree, unused). If neither passes, the B-spline result is kept and
    `--check` reports what it built."""
    doc = f.Document
    doc.recompute()
    base = getattr(f, "BaseFeature", None)
    if base is None or base.Shape.isNull():
        return

    def holds():
        sh = f.Shape
        if sh.isNull() or not sh.isValid():
            return False
        vb, va, vt = base.Shape.Volume, sh.Volume, abs(analytic.Shape.Volume)
        removed = vb - va
        return -1e-6 * vb <= removed <= 1.02 * vt + 1e-4 * vb

    if holds():
        return
    nurbs = list(f.Group)
    f.setObjects([analytic])
    doc.recompute()
    if holds():
        f.Label = (f.Label + " (analytic cutter: the B-spline cut did not hold)")[:120]
        return
    f.setObjects(nurbs)
    doc.recompute()


def _boolean(body, tools, name, kind, label=None):
    """PartDesign Boolean of `body` with tool bodies: kind Fuse / Cut / Common.
    Exact (FuzzyTolerance 0): on FreeCAD's OCCT a fuzzy 0.01 can produce an
    invalid shape.

    A Boolean's group CLAIMS its tools: handing the same tool body to a second
    Boolean silently takes it away from the first, which then clips to nothing.
    A cut or intersect of a multi-body part needs one Boolean per body with the
    same tool, so a tool already claimed goes in through a SubShapeBinder."""
    ops = []
    for t in tools:
        if any(p.TypeId == "PartDesign::Boolean" for p in t.InList):
            ref = body.Document.addObject("PartDesign::SubShapeBinder", f"{name}_Ref")
            ref.Support = [(t, "")]
            _hide(ref)
            t = ref
        ops.append(t)
    f = _plain(body.newObject("PartDesign::Boolean", name))
    f.Type = kind
    f.addObjects(ops)
    if label:
        f.Label = label
    return _tip(body, f)


def _nurbs_tool(doc, name, analytic, label=None):
    """A tool body whose solid is `analytic`'s shape as B-splines.

    OCC cuts a tilted cone or cylinder out of a revolved body wrongly, and
    silently, in analytic form: the analytic groove can remove too much and
    not mesh closed; the same tool as B-splines is right. The
    analytic body stays in the tree (hidden) as the parametric source; the
    B-spline copy is stored, and this program regenerates it on every run."""
    doc.recompute()
    nf = doc.addObject("Part::Feature", name + "_Nurbs")
    nf.Shape = _baked(analytic.Shape.toNurbs())
    _hide(nf)
    tb = _body(doc, name, label=label, tool=True)
    tb.BaseFeature = nf
    return tb


# ---- reading the part back ---------------------------------------------------------
def _op(f):
    t = f.TypeId
    if t in _ADD or t.startswith("PartDesign::Additive"):
        return "add"
    if t in _CUT or t.startswith("PartDesign::Subtractive"):
        return "cut"
    return None


def _chain(body):
    """The Body's features from first to Tip, following BaseFeature."""
    out, f = [], body.Tip
    while f is not None and f in body.Group:
        out.append(f)
        f = getattr(f, "BaseFeature", None)
    return out[::-1]


def _feature_steps(f):
    """[(op, shape)] one feature contributes, its own tool solids, as copies."""
    op = _op(f)
    if op:
        return [(op, f.AddSubShape.copy())]
    if f.TypeId in _PATTERNS:
        flat = list(f.M2C_Transforms) if hasattr(f, "M2C_Transforms") else []
        mats = [App.Matrix(*flat[i:i + 16]) for i in range(0, len(flat), 16)]
        out = []
        for o in f.Originals:
            o_op = _op(o)
            if not o_op:
                continue
            for m in mats:
                s = o.AddSubShape.copy()
                s.transformShape(m)
                out.append((o_op, s))
        return out
    if f.TypeId == "PartDesign::Boolean":
        tools = [b.Shape.copy() for b in f.Group]
        tool = tools[0] if len(tools) == 1 else Part.makeCompound(tools)
        return [({"Fuse": "add", "Cut": "cut", "Common": "intersect"}[f.Type], tool)]
    return []


def _volume_before_last(doc, bodies):
    """What the part Bodies held just before the last feature block -- the
    first object of that block in each Body's chain, and what it was built on
    -- so the harness can say when a feature changed nothing. None when it
    cannot be read."""
    import re as _re
    blocks = sorted({m.group(1) for o in doc.Objects
                     for m in [_re.match(r"(F\d+)_", o.Name)] if m})
    if not blocks:
        return None
    last, total = blocks[-1] + "_", 0.0
    try:
        for b in bodies:
            first = next((f for f in _chain(b) if f.Name.startswith(last)), None)
            if first is None:
                if not b.Name.startswith(last) and not b.Shape.isNull():
                    total += b.Shape.Volume
            elif first.BaseFeature is not None and not first.BaseFeature.Shape.isNull():
                total += first.BaseFeature.Shape.Volume
        return total
    except Exception:                                              # noqa: BLE001
        return None


def _finish(doc):
    """Recompute, then read the part back from the tree: (result, steps).

    Steps run over every part body in creation order; a body after the first
    starts with a "body" step, as `--combine separate` did. Tool bodies are
    not part of the part: they enter through the Boolean that uses them."""
    doc.recompute()
    bodies = _part_bodies(doc)
    index = {o.Name: i for i, o in enumerate(doc.Objects)}
    feats = []
    for k, b in enumerate(bodies):
        first = True
        if b.BaseFeature is not None:
            feats.append((index[b.Name], "add" if k == 0 else "body",
                          b.BaseFeature.Shape.copy(), b.BaseFeature.Name))
            first = False
        for f in _chain(b):
            for op, s in _feature_steps(f):
                if first and k > 0 and op == "add":
                    op = "body"
                first = False
                feats.append((index[f.Name], op, s, f.Name))
    feats.sort(key=lambda x: x[0])
    shapes = [b.Shape.copy() for b in bodies]
    result = shapes[0] if len(shapes) == 1 else Part.makeCompound(shapes)
    save_as = globals().get("_M2C_SAVE_AS")
    if save_as:
        doc.saveAs(save_as)
    if App.GuiUp:
        import FreeCADGui
        FreeCADGui.SendMsgToActiveView("ViewFit")
    # Which object each step came from (F03_Pad, F03_Cut ...): the harness
    # reads it to say what a feature built on its own.
    globals()["_STEP_NAMES"] = [n for *_, n in feats]
    globals()["_VOLUME_BEFORE_LAST"] = _volume_before_last(doc, bodies)
    return result, [(op, s) for _, op, s, _n in feats]
