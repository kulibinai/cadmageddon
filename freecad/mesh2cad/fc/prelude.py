"""The helpers every m2c FreeCAD program carries.

An emitted program is self-contained: the block between the two marker lines
below is copied verbatim to the top of it (`mesh2cad.fc.prelude_source()`), so
the program runs in stock FreeCAD -- as a GUI macro or with FreeCADCmd -- with
no harness installed. Importing this module (tests do) defines the same
functions, so what is tested is exactly what is inlined.

The program contract:

    doc, body = _start("reconstruction")

    # sketch on XY at Z = 2.5100            <- the header `sketch` writes
    # extrude: Z=2.2600 to Z=2.7600 ...
    _b = _block(doc, "F01", "add", "#01 extrude XY Z 2.26->2.76")
    sk = _sketch(_b, _plane_at("XY", 2.51))
    _ring(sk, [...])
    _pad(_b, sk, 0.5, side="sym")
    _end(_b)
    ...
    result, _STEPS = _finish(doc)

A BLOCK is one harness feature. Its mode says what the feature does to the
part -- add, cut, intersect, or separate (a body of its own) -- and the block,
not the emitter, decides at run time where its features go:

  * add          into the last part Body (Pad, Revolution, ...)
  * cut          straight into the part Body as Pocket / Groove / Subtractive*
                 when the part is one Body and the feature is plain;
  * otherwise    into a TOOL Body, joined to the part by PartDesign Booleans --
                 a cut or intersect of a multi-body part (one Boolean per
                 Body), a "mixed" feature
                 that removes from its own solid (a loft with holes, a coil
                 trimmed to its band: `_b.mixed = True`), and a cutter written
                 as B-splines (`_b.nurbs = True`, the tilted-bore fix);
  * separate     a new part Body.

So an emitter writes one feature the same way whatever the glue: the same
`_pad` is a Pad in an add block and a Pocket in a cut block. `minus=True`
marks a feature that removes from the block's own solid.

`result` is the part (one Body's shape, or a compound of the part bodies) and
`_STEPS` is `[(op, shape), ...]` read back from the TREE: every feature's own
tool solid (`AddSubShape`), in build order, op in add / cut / intersect / body.
`mesh2cad.build._mesh_steps` meshes those one by one and combines them with
manifold3d.

Edit this file, never a program: programs are regenerated.
"""

