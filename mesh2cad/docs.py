"""Generate the agent-facing instrument reference from the real CLI.

Two documents describe the instruments. `prompts/reconstruction.md` is prose: it
says how to think, in what order to work, and why. `prompts/instruments.md` is
the reference: every command, every flag, generated from the parser that will
actually run. Only the first is written by hand.

The split exists because the reference is the part that rots. A flag renamed in
code and not in the doc sends an agent into a loop of failed calls, and the
agent has no way to tell that the doc is wrong rather than itself. Generating it
from `build_parser()` makes that class of drift impossible, and CI fails if the
checked-in copy is stale.
"""

import argparse
import importlib.util
from pathlib import Path

from mesh2cad import registry

ROOT = Path(__file__).resolve().parent.parent
CLI = ROOT / "scripts" / "m2c.py"
TARGET = ROOT / "prompts" / "instruments.md"

HEADER = """<!-- GENERATED by `make docs` from scripts/m2c.py and the registry.
     Do not edit: your change will be overwritten and CI will fail on it.
     To change what this says, change the argparse help or the contribution's
     summary. The prose companion, which IS hand-written, is
     reconstruction.md. -->

# Instruments

Every command takes a mesh and prints a compact text block; some also write a
PNG, announced by an `IMAGE:` line. Nothing here needs a coordinate typed by
hand -- each one names what it found, and the name is what you pass on.

    m2c.py [--out DIR] <command> [options]

"""


def load_cli():
    spec = importlib.util.spec_from_file_location("m2c_cli", CLI)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def render():
    parser = load_cli().build_parser()
    sub = _subparsers(parser)
    contributed = {c.name: c for c in registry.entries("instrument")}

    out = [HEADER]
    for name, p in sub.items():
        entry = contributed.get(name)
        out.append(f"## `{name}`\n")
        out.append(f"{(p.description or _help_of(parser, name) or '').strip()}\n")
        if entry:
            out.append(f"*Contributed by {entry.author or 'unknown'} "
                       f"(`{entry.module}`).*\n")
        out.append("```\n" + _usage(p, name) + "```\n")
        rows = _options(p)
        if rows:
            out.append("| option | meaning |\n|---|---|\n")
            for flag, helptext in rows:
                out.append(f"| `{_cell(flag)}` | {_cell(helptext)} |\n")
        out.append("\n")

    parts = registry.entries("part")
    policies = registry.entries("policy")
    skills = registry.entries("skill")
    for title, group in (("Benchmark parts", parts), ("Policies", policies),
                         ("Claude Code skills", skills)):
        if not group:
            continue
        out.append(f"## {title}\n\n")
        for c in group:
            out.append(f"- **{c.name}** -- {c.summary}"
                       + (f" ({c.author})" if c.author else "") + "\n")
        out.append("\n")
    return "".join(out)


def _subparsers(parser):
    for action in parser._actions:
        if isinstance(action, argparse._SubParsersAction):
            return dict(action.choices)
    return {}


def _help_of(parser, name):
    for action in parser._actions:
        if isinstance(action, argparse._SubParsersAction):
            for ch in action._get_subactions():
                if ch.dest == name:
                    return ch.help
    return ""


def _usage(p, name):
    """The synopsis, with every placeholder in angle brackets.

    It used to render as `m2c.py sketch mesh --plane PLANE --at AT [options]`,
    which is indistinguishable from a command, sits in a bash fence, and is the
    first thing under each heading. A model copied that line verbatim 56 times
    in one run -- every one rejected by argparse, every one costing a call, the
    whole 40-call budget spent on a template. Angle brackets cannot be mistaken
    for values, and `<mesh>` is visibly not a filename.
    """
    positionals = [f"<{a.dest}>" for a in p._actions if not a.option_strings
                   and a.dest != "help"]
    req = []
    for a in p._actions:
        if not (a.option_strings and a.required):
            continue
        if a.nargs == 0:
            req.append(a.option_strings[0])
        elif a.choices:
            req.append(f"{a.option_strings[0]} <{'|'.join(map(str, a.choices))}>")
        else:
            req.append(f"{a.option_strings[0]} <{a.dest}>")
    bits = ["m2c.py", name] + positionals + req
    return " ".join(bits) + " [options]\n"


def _options(p):
    rows = []
    for a in p._actions:
        if not a.option_strings or a.dest == "help":
            continue
        flag = ", ".join(a.option_strings)
        if a.choices:
            flag += " {" + "|".join(str(c) for c in a.choices) + "}"
        elif a.nargs != 0:
            flag += " " + a.dest.upper()
        rows.append((flag, (a.help or "").replace("\n", " ").strip()))
    return rows


def _cell(text):
    """Escape `|` for a Markdown table cell.

    A bare pipe ends the cell even inside backticks, so `{both|faces|sweep}`
    rendered as a truncated `{both` with the rest spilled into the next column.
    """
    return text.replace("|", "\\|")


def write():
    TARGET.parent.mkdir(parents=True, exist_ok=True)
    text = render()
    stale = not TARGET.exists() or TARGET.read_text() != text
    if stale:
        TARGET.write_text(text)
    return stale


def is_stale():
    return not TARGET.exists() or TARGET.read_text() != render()


if __name__ == "__main__":
    changed = write()
    print(f"{'wrote' if changed else 'unchanged'} {TARGET}")
